// start : program ;
std::any MyVisitor::visitStartRule(CSubset_2205091Parser::StartRuleContext *ctx) {
    visit(ctx->program());

    if (codeStream.is_open()) {
        dataSection += "minus_sign db '-'\n";
        dataSection += "newline_str db 10\n";
        dataSection += "char_buffer db 0\n";
        codeStream << "; Intermediate Code Generated by 2205091 (FASM x86)\n";
        codeStream << dataSection;
        codeStream << codeSection;

        // Standard OUTDEC Procedure for Printing Integers (Linux sys_write)
        codeStream << "OUTDEC:\n";
        codeStream << "    push eax\n";
        codeStream << "    push ebx\n";
        codeStream << "    push ecx\n";
        codeStream << "    push edx\n";
        codeStream << "    cmp eax, 0\n";
        codeStream << "    jge .positive\n";
        codeStream << "    neg eax\n";
        codeStream << "    push eax\n";
        codeStream << "    mov eax, 4\n";
        codeStream << "    mov ebx, 1\n";
        codeStream << "    mov ecx, minus_sign\n";
        codeStream << "    mov edx, 1\n";
        codeStream << "    int 0x80\n";
        codeStream << "    pop eax\n";
        codeStream << ".positive:\n";
        codeStream << "    xor ecx, ecx\n";
        codeStream << "    mov ebx, 10\n";
        codeStream << ".divide_loop:\n";
        codeStream << "    xor edx, edx\n";
        codeStream << "    div ebx\n";
        codeStream << "    push edx\n";
        codeStream << "    inc ecx\n";
        codeStream << "    cmp eax, 0\n";
        codeStream << "    jnz .divide_loop\n";
        codeStream << ".print_loop:\n";
        codeStream << "    pop edx\n";
        codeStream << "    add edx, '0'\n";
        codeStream << "    push ecx\n";
        codeStream << "    mov [char_buffer], dl\n";
        codeStream << "    mov eax, 4\n";
        codeStream << "    mov ebx, 1\n";
        codeStream << "    mov ecx, char_buffer\n";
        codeStream << "    mov edx, 1\n";
        codeStream << "    int 0x80\n";
        codeStream << "    pop ecx\n";
        codeStream << "    loop .print_loop\n";
        codeStream << "    mov eax, 4\n";
        codeStream << "    mov ebx, 1\n";
        codeStream << "    mov ecx, newline_str\n";
        codeStream << "    mov edx, 1\n";
        codeStream << "    int 0x80\n";
        codeStream << "    pop edx\n";
        codeStream << "    pop ecx\n";
        codeStream << "    pop ebx\n";
        codeStream << "    pop eax\n";
        codeStream << "    ret\n\n";

        codeStream.close();
    }
    return nullptr;
}

