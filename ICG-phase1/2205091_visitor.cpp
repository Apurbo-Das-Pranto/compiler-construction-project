std::any MyVisitor::visitRelExprBinary(CSubset_2205091Parser::RelExprBinaryContext *ctx) {
    visit(ctx->simple_expression(0));
    visit(ctx->simple_expression(1));

    codeSection += "    pop ebx\n";
    codeSection += "    pop eax\n";
    codeSection += "    cmp eax, ebx\n";

    string op = ctx->RELOP()->getText();
    string labelTrue = newLabel();
    string labelEnd = newLabel();

    if (op == "<") codeSection += "    jl " + labelTrue + "\n";
    else if (op == "<=") codeSection += "    jle " + labelTrue + "\n";
    else if (op == ">") codeSection += "    jg " + labelTrue + "\n";
    else if (op == ">=") codeSection += "    jge " + labelTrue + "\n";
    else if (op == "==") codeSection += "    je " + labelTrue + "\n";
    else if (op == "!=") codeSection += "    jne " + labelTrue + "\n";

    codeSection += "    push 0\n";
    codeSection += "    jmp " + labelEnd + "\n";
    codeSection += labelTrue + ":\n";
    codeSection += "    push 1\n";
    codeSection += labelEnd + ":\n";

    return nullptr;
}

