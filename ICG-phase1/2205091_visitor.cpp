std::any MyVisitor::visitSimpleExprAdd(CSubset_2205091Parser::SimpleExprAddContext *ctx) {
    visit(ctx->simple_expression());
    visit(ctx->term());

    codeSection += "    pop ebx\n";
    codeSection += "    pop eax\n";

    string op = ctx->ADDOP()->getText();
    if (op == "+") {
        codeSection += "    add eax, ebx\n";
    } else if (op == "-") {
        codeSection += "    sub eax, ebx\n";
    }
    codeSection += "    push eax\n";
    return nullptr;
}

