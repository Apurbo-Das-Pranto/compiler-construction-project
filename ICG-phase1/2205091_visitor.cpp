// Constructor & Destructor


MyVisitor::MyVisitor(int bucketSize, string outputFile) {
    symbolTable = new SymbolTable(bucketSize);
    codeStream.open(outputFile);
    labelCounter = 0;
    nextLocalOffset = -4;
    nextParamOffset = 8;
    currentFunctionName = "";

    // FASM ELF Executable Directive Initialization
    dataSection = "format ELF executable 3\nentry main\n\nsegment readable writeable\n";
    codeSection = "\nsegment readable executable\n\n";
}


// Helper Functions

bool MyVisitor::isGlobalScope() {
    return symbolTable->getCurrentScopeTable()->getParentScopeTable() == nullptr;
}

string MyVisitor::getOperand(string name) {
    SymbolInfo *symbol = symbolTable->lookUpSymbolInfo(name);
    if (symbol == nullptr) return name;

    if (symbol->getIsGlobal()) {
        return "[" + name + "]";
    } else {
        int offset = symbol->getOffset();
        if (offset < 0) {
            return "[ebp" + to_string(offset) + "]";
        } else {
            return "[ebp+" + to_string(offset) + "]";
        }
    }
}

string MyVisitor::newLabel() {
    return "L" + to_string(labelCounter++);
}

void MyVisitor::annotateLine(antlr4::ParserRuleContext *ctx) {
    if (ctx && ctx->getStart()) {
        int line = ctx->getStart()->getLine();
        codeSection += "; Line " + to_string(line) + "\n";
    }
}


