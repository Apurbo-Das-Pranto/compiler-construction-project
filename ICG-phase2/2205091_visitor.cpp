std::any MyVisitor::visitVarArray(CSubset_2205091Parser::VarArrayContext *ctx) {
    string name = ctx->ID()->getText();
    SymbolInfo *symbol = symbolTable->lookUpSymbolInfo(name);

    visit(ctx->expression());

    codeSection += "    pop eax\n";
    codeSection += "    shl eax, 2\n";

    if (symbol->getIsGlobal()) {
        codeSection += "    add eax, " + name + "\n";
    } else {
        int baseOffset = symbol->getOffset();
        codeSection += "    mov ebx, ebp\n";
        codeSection += "    add ebx, " + to_string(baseOffset) + "\n";
        codeSection += "    sub ebx, eax\n";
        codeSection += "    mov eax, ebx\n";
    }

    codeSection += "    push eax\n";
    return name;
}

