std::any MyVisitor::visitFactorFuncCall(CSubset_2205091Parser::FactorFuncCallContext *ctx) {
    annotateLine(ctx);
    string funcName = ctx->ID()->getText();

    vector<antlr4::ParserRuleContext*> args;
    if (ctx->argument_list()) {
        auto res = visit(ctx->argument_list());
        if (res.has_value()) {
            args = std::any_cast<vector<antlr4::ParserRuleContext*>>(res);
        }
    }

    // Push arguments in reverse order (
    for (int i = (int)args.size() - 1; i >= 0; i--) {
        visit(args[i]); 
    }

    codeSection += "    call " + funcName + "\n";

    if (!args.empty()) {
        codeSection += "    add esp, " + to_string(args.size() * 4) + "\n";
    }

    codeSection += "    push eax\n";
    return nullptr;
}

