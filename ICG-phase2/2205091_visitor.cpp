std::any MyVisitor::visitFuncDefNoParams(CSubset_2205091Parser::FuncDefNoParamsContext *ctx) {
    visit(ctx->type_specifier());
    string funcName = ctx->ID()->getText();
    currentFunctionName = funcName;

    codeSection += funcName + ":\n";
    codeSection += "    push ebp\n";
    codeSection += "    mov ebp, esp\n";

    nextLocalOffset = -4;

    SymbolInfo *s = new SymbolInfo(funcName, "ID");
    s->setIsFunction(true);
    s->setIsDefined(true);
    s->setDataType(currentType);
    symbolTable->insertSymbolInfo(s);

    symbolTable->enterScope();
    visit(ctx->compound_statement());
    symbolTable->exitScope();

    if (funcName == "main") {
        if (!endsWithSyscall(codeSection)) {
            codeSection += "    mov eax, 1\n";
            codeSection += "    xor ebx, ebx\n";
            codeSection += "    int 0x80\n";
        }
    } else {
        if (!endsWithRet(codeSection)) {
            codeSection += "    mov esp, ebp\n";
            codeSection += "    pop ebp\n";
            codeSection += "    ret\n";
        }
    }
    return nullptr;
}

