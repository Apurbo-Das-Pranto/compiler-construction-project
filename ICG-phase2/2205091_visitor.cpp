std::any MyVisitor::visitLogicExprBinary(CSubset_2205091Parser::LogicExprBinaryContext *ctx) {
    string op = ctx->LOGICOP()->getText();
    string labelShortCircuit = newLabel();
    string labelEnd = newLabel();

    visit(ctx->rel_expression(0)); 
    codeSection += "    pop eax\n";                
    codeSection += "    cmp eax, 0\n";

    if (op == "&&") {
        codeSection += "    je " + labelShortCircuit + "\n";   
    } else {
        codeSection += "    jne " + labelShortCircuit + "\n";  
    }

    visit(ctx->rel_expression(1));                
    codeSection += "    pop eax\n";
    codeSection += "    cmp eax, 0\n";

    if (op == "&&") {
        codeSection += "    je " + labelShortCircuit + "\n";
        codeSection += "    push 1\n";
    } else {
        codeSection += "    jne " + labelShortCircuit + "\n";
        codeSection += "    push 0\n";
    }
    codeSection += "    jmp " + labelEnd + "\n";

    codeSection += labelShortCircuit + ":\n";
    codeSection += (op == "&&" ? "    push 0\n" : "    push 1\n");

    codeSection += labelEnd + ":\n";
    return nullptr;
}

