std::any MyVisitor::visitStmtFor(CSubset_2205091Parser::StmtForContext *ctx) {
    annotateLine(ctx);

    string startLabel = newLabel();
    string exitLabel = newLabel();

    if (ctx->init) {
        visit(ctx->init);
    }

    codeSection += startLabel + ":\n";

    if (ctx->cond) {
        auto exprStmt = dynamic_cast<CSubset_2205091Parser::ExprStmtExprContext*>(ctx->cond);
        if (exprStmt) {
            visit(exprStmt);
            codeSection += "    cmp eax, 0\n";
            codeSection += "    je " + exitLabel + "\n";
        }
    }

    if (ctx->body) {
        visit(ctx->body);
    }

    if (ctx->incr) {
        visit(ctx->incr);
        codeSection += "    pop eax\n";
    }

    codeSection += "    jmp " + startLabel + "\n";
    codeSection += exitLabel + ":\n";

    return nullptr;
}

